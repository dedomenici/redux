import json,math,re
rows=json.load(open('all_rows.json'))
def dist(a,b,c,d): return 6371*2*math.asin(math.sqrt(math.sin(math.radians(c-a)/2)**2+math.cos(math.radians(a))*math.cos(math.radians(c))*math.sin(math.radians(d-b)/2)**2))
spots=[]
for r in sorted(rows,key=lambda r:(r['coord_conf']!='high',r['coord_conf']!='medium')):
    nm=r['place_zh'] or r['place_en']
    s=next((s for s in spots if dist(s['lat'],s['lng'],r['lat'],r['lng'])<0.06 or (dist(s['lat'],s['lng'],r['lat'],r['lng'])<0.25 and (nm==s['nameZh'] or nm==s['name']))),None)
    if not s:
        s=dict(name=r['place_en'] or r['place_zh'],nameZh=r['place_zh'],city=r['city'],lat=round(r['lat'],6),lng=round(r['lng'],6),precision='street' if r['coord_conf']=='street-level' else ('exact site' if r['coord_conf']=='high' else 'site'),coordSource=r['coord_source'][:140],films=[])
        spots.append(s)
    if not s['nameZh'] and r['place_zh']: s['nameZh']=r['place_zh']
    if s['name']==s['nameZh'] and r['place_en']: s['name']=r['place_en']
    title=r['film_en'] or r['film_zh']
    if any((f['title'],f.get('year'))==(title,r['year']) for f in s['films']): continue
    f=dict(title=title,kind=r['kind'],source=r['source'],confidence=r['link_conf'])
    if r['film_zh'] and r['film_zh']!=title: f['titleZh']=r['film_zh']
    if r['year']: f['year']=r['year']
    if r['scene']: f['scene']=r['scene'][:240]
    s['films'].append(f)
for i,s in enumerate(spots):
    s['id']='tw-%03d-%s'%(i+1,re.sub(r'[^a-z0-9]+','-',(s['name'] if s['name'].isascii() else 'place').lower()).strip('-')[:40])
    if not s['nameZh'] or s['nameZh']==s['name']: s.pop('nameZh',None)
json.dump(spots,open('spots.json','w'),ensure_ascii=False,indent=1)
from collections import Counter
print(len(spots),'spots',Counter(s['city'] for s in spots))
